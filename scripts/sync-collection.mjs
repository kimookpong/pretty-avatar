// Publish only individually reviewed and numerically verified generated characters.
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs'
const root = new URL('../', import.meta.url)
const dir = new URL('public/avatars/', root)
const catalog = JSON.parse(readFileSync(new URL('skills/pretty-avatar/reference/catalog.json', root), 'utf8'))
const byId = new Map(catalog.map((item) => [item.id, item]))
const ready = []
for (const file of readdirSync(dir).filter((name) => name.endsWith('.json')).sort()) {
  const metadata = JSON.parse(readFileSync(new URL(file, dir), 'utf8'))
  const preset = byId.get(metadata.id)
  if (!preset || metadata.status !== 'verified' || !metadata.visual_review || !metadata.report?.ok) continue
  for (const kind of ['directions', 'reactions']) {
    if (!existsSync(new URL(`${preset.id}-${kind}.webp`, dir))) throw new Error(`Missing ${preset.id}-${kind}.webp`)
  }
  ready.push({ name: preset.id, category: preset.category, en: preset.id.replace(/^(animal|human)-/, '').replaceAll('-', ' '), th: preset.label_th })
}
const target = new URL('site/generated-cast.ts', root)
const content = `// Generated by scripts/sync-collection.mjs from verified avatar metadata.\nexport const GENERATED_CAST = ${JSON.stringify(ready, null, 2)} as const\n`
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== content) {
    throw new Error('Generated cast is stale. Run npm run sync:collection')
  }
} else {
  writeFileSync(target, content)
  console.log(`Generated cast: ${ready.length}/60 ready (${ready.filter((item) => item.category === 'animal').length} animals, ${ready.filter((item) => item.category === 'human').length} humans)`)
}

const readyTarget = new URL('skills/pretty-avatar/reference/ready-collection.md', root)
const readyText = '# Ready-made generated collection\n\nGenerated by `scripts/sync-collection.mjs`. Only characters with verified atlases and completed visual review appear here.\n\n' + ready.map((item) => `- \`${item.name}\` — ${item.th} (${item.category})`).join('\n') + '\n\nThe two filenames are `<name>-directions.webp` and `<name>-reactions.webp`.\nUse local `public/avatars/` files when working in this repository. A local generated file does not prove the live website has deployed it; verify remote availability before downloading it in another project.\n'
if (process.argv.includes('--check')) {
  if (!existsSync(readyTarget) || readFileSync(readyTarget, 'utf8') !== readyText) throw new Error('Ready-made collection reference is stale. Run npm run sync:collection')
} else {
  writeFileSync(readyTarget, readyText)
}
